@dataclass(frozen=True)
class Instruments:
    """What the driver measures the scope's pool with: the inputs of `phases.run`, the probes the
    booking's wait reads, the release the hosts must serve and the commit the run is of. The
    operator-side driver assembles them for the selected pool (its canary identities, its
    telemetry workspace, its trial image and harness workers); every one names that pool."""

    gateway: replay.Gateway
    canaries: phases.Canaries
    telemetry: phases.Telemetry
    artifacts: phases.Artifacts
    harnesses: trials.Harnesses
    graders: Mapping[Family, trials.Grader]
    gateway_ready: Callable[[], bool]
    releases: Callable[[], Sequence[str]]
    release: str
    source_commit: str


def _tally(tally: Any) -> SendTally | None:
    if tally is None:
        return None
    failures = {outcome.value: count for outcome, count in tally.failures.items()}
    return SendTally(
        attempts=tally.attempts,
        unfinished=tally.unfinished,
        completed=tally.completed,
        truncated_stream=failures.get("truncated_stream", 0),
        transport_error=failures.get("transport_error", 0),
        http_refusal=failures.get("http_refusal", 0),
        error_event=failures.get("error_event", 0),
        retries=tally.retries,
        usage_missing=tally.usage_missing,
        eligible=tally.eligible,
    )


def _hosts(reading: Any) -> list[HostLaunch]:
    """Each host's launch, as a checkpoint keeps it: its one fingerprint, and whether the launch
    series said it through the host's time in service. A gap in that series is no whole window,
    whatever the release series shows of the host."""
    hosts = []
    for host in () if reading is None else reading.hosts:
        said = set(host.launch_fingerprints)
        hosts.append(
            HostLaunch(
                host=host.host,
                in_service_ms=round(host.in_service_seconds * 1000),
                launch_fingerprint=next(iter(said)) if len(said) == 1 else None,
                launch_whole_window=len(said) == 1 and host.launch_whole_window,
            )
        )
    return hosts


def keep_evidence(
    journal: Journal,
    attempt: int,
    *,
    tally: SendTally | None,
    hosts: Sequence[HostLaunch],
    requested_launch_fingerprint: str | None,
    origin_s: float,
) -> None:
    """Saves what the bundle needs of an attempt beside the journal, before its checkpoint: the
    scheduler's tally, the serving hosts, the requested launch fingerprint, and the time in
    seconds since the epoch at which the booking's run clock read zero (`origin_s`)."""
    folder = journal.directory / EVIDENCE
    folder.mkdir(mode=0o700, exist_ok=True)
    saved = {
        "tally": None if tally is None else tally.to_json(),
        "hosts": [host.to_json() for host in hosts],
        "requested_launch_fingerprint": requested_launch_fingerprint,
        "origin_s": origin_s,
    }
    _write_json(folder / f"attempt-{attempt}.json", saved)


_TIMES = ("started_ms", "admissions_ended_ms", "ended_ms", "eligible_ms", "sent_ms", "first_output_ms")
_TIMES += ("first_answer_ms", "last_output_ms", "at_ms")


def _shifted[D: Document](document: D, offset_ms: int) -> D:
    """A record or an observation moved `offset_ms` later on the run's timeline."""
    if not offset_ms or not isinstance(document, CellRecord | RequestRecord | TrialRecord | HostSample):
        return document
    names = {one.name for one in dataclasses.fields(document)}
    moved = {
        name: value + offset_ms
        for name in _TIMES
        if name in names and isinstance(value := getattr(document, name), int)
    }
    return dataclasses.replace(document, **moved)


def _times(document: Document) -> list[int]:
    names = {one.name for one in dataclasses.fields(document)} if dataclasses.is_dataclass(document) else set()
    return [value for name in _TIMES if name in names and isinstance(value := getattr(document, name), int)]


def write_bundle(journal: Journal, directory: Path) -> bool:
    """Writes the run's evidence bundle into `directory`, which does not exist, from the journal
    and the evidence kept at each checkpoint: every checkpointed attempt, in order, but a valid
    one a later attempt of its cell superseded (an earlier booking's warm-up). Each booking
    measures on a run clock of its own (its `origin_s`); its times are laid on one timeline, the
    millisecond after the booking before it ends, so that the bundle keeps the order and the
    measured durations of every cell, and none of the time between bookings: a week away is no
    week of evidence. False with no evidence; `report.ReportError` (`unreadable-bundle`) when the
    evidence of a checkpointed attempt cannot be read, so that no report omits a measured cell."""
    manifest_file = journal.directory / phases.MANIFEST
    if not manifest_file.exists():
        return False
    manifest = loads(manifest_file.read_text(encoding="utf-8"), Manifest)
    bookings: list[tuple[float, list[tuple[journals.Attempt, dict[str, Any], tuple[Document, ...]]]]] = []
    for attempt in journal.attempts:
        if attempt.status is not AttemptStatus.COMPLETE or attempt.record is None:
            continue
        if attempt.record.valid_for_qualification and attempt.replaced_by is not None:
            # Superseded, as each booking's warm-up supersedes the one before: a cell is read once.
            continue
        extra = _read_json(journal.directory / EVIDENCE / f"attempt-{attempt.ordinal}.json")
        if extra is None:
            # A checkpointed cell whose evidence cannot be read: a bundle without it would claim
            # a result for cells it does not hold.
            raise report.ReportError(report.Refusal.UNREADABLE_BUNDLE)
        origin = float(extra.get("origin_s") or 0.0)
        if not bookings or bookings[-1][0] != origin:
            bookings.append((origin, []))
        bookings[-1][1].append((attempt, extra, tuple(journal.observations(attempt.ordinal))))
    attempts = []
    end: int | None = None
    for _, held in bookings:
        times = [at for attempt, _, seen in held for one in (attempt.record, *seen) if one is not None for at in _times(one)]
        offset = 0 if end is None or not times else end + 1 - min(times)
        end = max((at + offset for at in times), default=end)
        for attempt, extra, seen in held:
            assert attempt.record is not None
            tally = None if extra["tally"] is None else SendTally.from_json(extra["tally"], "tally")
            hosts = tuple(HostLaunch.from_json(one, "host") for one in extra["hosts"])
            attempts.append(
                report.Evidence(
                    _shifted(attempt.record, offset),
                    tuple(_shifted(one, offset) for one in seen),
                    tally,
                    hosts,
                    extra["requested_launch_fingerprint"],
                )
            )
    if not attempts:
        return False
    report.write_evidence(directory, manifest, attempts)
    return True


class LiveRuntime:
    """The runtime of a real invocation: the driver's own AWS session, GitHub with the driver's
    token in the scope's repository, and the instruments of the scope's pool: given, or resolved
    from that session and this host at the preflight (`evaluate.live.resolve`), and released
    with the invocation."""

    def __init__(
        self,
        scope: Scope,
        *,
        instruments: Instruments | None,
        token: str | None,
        session: Callable[[], Any],
        environ: Mapping[str, str] | None = None,
    ) -> None:
        self.scope, self._instruments, self._token, self._session = scope, instruments, token, session
        self._environ = {} if environ is None else environ
        self._github: publisher.GitHub | None = None
        self._access: booking.Access | None = None
        self._aws: Any = None
        self.stack = contextlib.ExitStack()

    def github(self) -> publisher.GitHub:
        if self._github is None:
            self._github = publisher.GitHub(publisher.HttpTransport(self._token or ""), self.scope.repository)
        return self._github

    def _aws_session(self) -> Any:
        if self._aws is None:
            self._aws = self._session()
        return self._aws

    def _held(self) -> Instruments:
        if self._instruments is None:
            raise ControllerError(Check.MEASUREMENT)
        return self._instruments

    def access(self) -> booking.Access:
        """The pools' sessions, from the driver's session alone (`evaluate.live.pool_sessions`: the
        pools stack and `session_max_hours`, nothing of the students or the rest of the
        configuration): a restart whose instruments cannot be resolved still reconciles and stops
        what its run booked. The probes
        are the scope's pool's, and answer not ready while its instruments are not resolved."""
        if self._access is None:
            from evaluate import live

            try:
                sessions = live.pool_sessions(self._aws_session())
            except (*_UNREAD, KeyError, TypeError, ValueError) as error:
                raise ControllerError(Check.DEPLOYMENT) from error

            def gateway_ready() -> bool:
                return self._instruments is not None and self._instruments.gateway_ready()

            def releases() -> Sequence[str]:
                return () if self._instruments is None else self._instruments.releases()

            # Bound to the scope's pool: its gateway's readiness, and the release each of its hosts serves.
            self._access = booking.Access(sessions, gateway_ready, releases)
        return self._access

    def clock(self) -> float:
        return time.time()

    def release(self) -> str:
        return self._held().release

    def requested(self) -> Settings:
        return self._held().telemetry.requested.settings

    def source_commit(self) -> str:
        return self._held().source_commit

    def preflight(self, plan: Plan) -> list[str]:
        """The checks the measurement fails, each against what the plan needs of the scope's
        pool: the instruments resolved for it, the harness versions, the cohort the plan runs as
        (distinct keys, each with an alias of its own, as `phases.cohort` takes them), and the
        pool's telemetry answering the reader as a reading asks it (`telemetry.preflight`)."""
        if self._instruments is None:
            from evaluate import live

            try:
                self._instruments = live.resolve(self.scope, plan, self._aws_session(), self._environ, self.stack)
            except live.Unresolved as missing:
                return [missing.check]
        held, failed = self._instruments, []
        if not self._token:
            failed.append(Check.DESTINATION)
        if held.gateway.model != self.scope.pool or held.telemetry.pool != self.scope.pool:
            failed.append(Check.BINDING)
        try:
            versions = phases.installed_versions(held.artifacts.trial_image)
            if any(versions.get(pin.harness) != pin.version for pin in plan.workload.harnesses):
                failed.append(Check.HARNESS_VERSIONS)
        except (phases.PhaseError, OSError, subprocess.SubprocessError):
            # The image could not say, or did not answer in time.
            failed.append(Check.HARNESS_VERSIONS)
        try:
            phases.cohort(plan, held.canaries)
        except phases.PhaseError:
            failed.append(Check.CANARIES)
        source = held.telemetry
        try:
            telemetry.preflight(source.reader, source.pool, source.engine, time.time())
        except (OSError, ValueError):
            failed.append(Check.TELEMETRY)
        return failed

    async def measure(
        self,
        plan: Plan,
        admitted: phases.Admitted,
        journal: Journal,
        cells: Sequence[int],
        *,
        cancel: asyncio.Event,
        deadline_s: float,
    ) -> phases.Ended:
        held = self._held()
        origin_s = time.time() - held.gateway.clock.now_ms() / 1000

        def keep(attempt: int, tally: Any, reading: telemetry.Reading) -> None:
            keep_evidence(
                journal,
                attempt,
                tally=_tally(tally),
                hosts=_hosts(reading),
                requested_launch_fingerprint=reading.requested_launch_fingerprint,
                origin_s=origin_s,
            )

        result = await phases.run(
            plan,
            admitted,
            held.gateway,
            held.canaries,
            held.telemetry,
            held.artifacts,
            held.harnesses,
            held.graders,
            journal,
            origin_s=origin_s,
            cells=cells,
            cancel=cancel,
            deadline_ms=round((deadline_s - origin_s) * 1000),
            keep=keep,
        )
        return result.ended

    def write_bundle(self, plan: Plan, journal: Journal, directory: Path) -> bool:
        del plan
        return write_bundle(journal, directory)


@contextlib.contextmanager
def connect_live(
    scope: Scope, *, instruments: Instruments | None = None, environ: Mapping[str, str] | None = None
) -> Generator[LiveRuntime]:
    """The live runtime of one invocation, for `scope`. The AWS session is the driver's own, made
    from its environment when the deployment is first read; the token is the driver's, from
    `GITHUB_TOKEN_VARIABLE`. Without `instruments`, the preflight resolves those of the scope's
    pool (`evaluate.live`); what they hold on this host is disposed of when the invocation ends."""
    found = os.environ if environ is None else environ

    def session() -> Any:
        import boto3

        return boto3.session.Session()

    runtime = LiveRuntime(
        scope, instruments=instruments, token=found.get(GITHUB_TOKEN_VARIABLE), session=session, environ=found
    )
    with runtime.stack:
        yield runtime


def source_commit(repository: Path = report.REPO) -> str:
    """The checkout's commit, which a run records as its source."""
    return subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=repository, check=True, capture_output=True, text=True
    ).stdout.strip()
