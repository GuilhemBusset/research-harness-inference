def status(root: Path, run_id: str, out: IO[str]) -> int:
    """What a run shows: its status file and its publication, read without taking the run."""
    try:
        state = saved_state(root, run_id)
    except ControllerError as refused:
        print(f"refused: {refused.reason}", file=out)
        return Exit.INCOMPLETE
    shown = _read_json(root / run_id / STATUS) or {}
    delivered, waiting = _deliveries(state)
    shown = {**shown, "run_id": run_id, "delivered": delivered, "waiting": waiting}
    for key in sorted(shown):
        print(f"{key}: {json.dumps(shown[key])}", file=out)
    print(f"publication: {'pending' if waiting else 'delivered'}", file=out)
    return 0


def cancel(root: Path, run_id: str, out: IO[str]) -> int:
    """Asks the driver that owns the run to stop: its watcher, or its wait for capacity, reads the
    request, stops admissions and releases the booking."""
    try:
        directory = _run_directory(root, run_id)
    except ControllerError as refused:
        print(f"refused: {refused.reason}", file=out)
        return Exit.INCOMPLETE
    _write_json(directory / CANCEL, {"requested": True})
    print(f"cancel requested: {run_id}", file=out)
    return 0


def _scope_of(root: Path, run_id: str, repository: str | None) -> Scope:
    saved = _read_json(_run_directory(root, run_id) / REQUEST)
    if saved is None:
        raise ControllerError(Refusal.NO_SUCH_RUN)
    return Scope(saved["pool"], repository or saved["repository"])


def publish_resume(root: Path, run_id: str, *, connect: Connect, out: IO[str], repository: str | None = None) -> int:
    """Delivery alone: the run's issue creation if it is in doubt, then its waiting comments. It
    books nothing and measures nothing. 0 once nothing waits, 2 otherwise."""
    try:
        scope = _scope_of(root, run_id, repository)
        with connect(scope) as runtime:
            box = publisher.resume_publication(root, run_id, publisher.Publisher(runtime.github()))
    except (ControllerError, JournalError, PublishError) as refused:
        print(f"refused: {refused}", file=out)
        return Exit.INCOMPLETE
    path = root / run_id / STATUS
    _write_json(path, {**(_read_json(path) or {}), "delivered": box.delivered, "waiting": box.waiting})
    if box.issue is not None:
        print(f"issue: {issue_url(scope.repository, box.issue)}", file=out)
    print(f"publication: {'pending' if box.waiting else 'delivered'} ({box.delivered} delivered)", file=out)
    return Exit.INCOMPLETE if box.waiting or box.issue is None else 0


_RELATIVE = {
    "pass": publisher.Relative.NO_DIFFERENCE,
    "fail": publisher.Relative.WORSE,
}


def _capacity_relative(reference: Verdict | None, candidate: Verdict | None) -> publisher.Relative:
    definite = (Verdict.PASS, Verdict.MEASURED_MISS)
    if reference not in definite or candidate not in definite:
        return publisher.Relative.INCONCLUSIVE
    if reference == candidate:
        return publisher.Relative.NO_DIFFERENCE
    return publisher.Relative.BETTER if candidate is Verdict.PASS else publisher.Relative.WORSE


def comparison_of(compared: Mapping[str, Any], reference_run: str, candidate_run: str) -> publisher.Comparison:
    """The comparison's comment fields: capacity by shape from the two scorecards, quality by
    shape from the paired decision at class load."""
    ours, theirs = scorecard(compared["candidate"]), scorecard(compared["reference"])
    quality: dict[Shape, publisher.Relative] = {}
    for decision in compared.get("decisions", []):
        if decision.get("load") != "class_load" or decision.get("shape") is None:
            continue
        relative = _RELATIVE.get(decision["outcome"], publisher.Relative.INCONCLUSIVE)
        lower = decision.get("lower_points")
        if relative is publisher.Relative.NO_DIFFERENCE and isinstance(lower, int | float) and lower > 0:
            relative = publisher.Relative.BETTER
        quality[Shape(decision["shape"])] = relative
    return publisher.Comparison(
        reference_run=reference_run,
        candidate_run=candidate_run,
        capacity={shape: _capacity_relative(theirs.capacity.get(shape), ours.capacity.get(shape)) for shape in Shape},
        quality=quality,
        bundle_digest=report.digest_of(report.dump(compared)),
    )


def compare_issue(
    root: Path,
    issue: int,
    reference_run: str,
    candidate_run: str,
    *,
    connect: Connect,
    out: IO[str],
    rate: tuple[float, str],
    repository: str | None = None,
) -> int:
    """The issue-backed comparison: two runs of the experiment's issue, compared from their local
    bundles, the comparison posted once on the issue from the candidate's journal."""
    try:
        for run_id in (reference_run, candidate_run):
            if saved_state(root, run_id).get("issue_number") != issue:
                raise ControllerError(Refusal.NOT_COMPARABLE)
        reference = report.load(root / reference_run / BUNDLE)
        candidate = report.load(root / candidate_run / BUNDLE)
        compared = report.compare(reference, candidate, usd_per_host_hour=rate[0], rate_source=rate[1])
        print(report.render_comparison(compared), end="", file=out)
        comment = comparison_of(compared, reference_run, candidate_run)
        scope = _scope_of(root, candidate_run, repository)
        with connect(scope) as runtime, Journal.open(root, candidate_run) as journal:
            driver = publisher.Publisher(runtime.github())
            try:
                box = driver.publish_comparison(journal, comment)
            except PublishError as refused:
                if refused.reason is not publisher.Refusal.ALREADY_QUEUED:
                    raise
                box = driver.flush(journal)
    except (ControllerError, JournalError, PublishError, report.ReportError) as refused:
        print(f"refused: {refused}", file=out)
        return Exit.INCOMPLETE
    print(f"issue: {issue_url(scope.repository, issue)}", file=out)
    print(f"publication: {'pending' if box.waiting else 'delivered'}", file=out)
    return Exit.INCOMPLETE if box.waiting else 0


