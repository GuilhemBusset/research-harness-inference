class _Invocation:
    def __init__(self, request: Request, plan: Plan, runtime: Runtime, root: Path, out: IO[str]) -> None:
        self.request, self.plan, self.runtime, self.root, self.out = request, plan, runtime, root, out
        self.github = runtime.github()
        self.publisher = publisher.Publisher(self.github)
        self.journal: Journal | None = None
        self.capacity: booking.Capacity | None = None
        self.cleanup = booking.Cleanup.NOT_OWNED
        self.reason: Reason | None = None
        self.ends_at: float | None = None
        self._access: booking.Access | None = None
        self._shown = -1

    # --- Output ---

    def say(self, text: str) -> None:
        print(text, file=self.out, flush=True)

    def status(self, **changes: Any) -> None:
        if self.journal is None:
            return
        path = self.journal.directory / STATUS
        _write_json(path, {**(_read_json(path) or {}), **changes})

    @property
    def access(self) -> booking.Access:
        """The pool's access, whose sleeps end at a cancel request: a wait for capacity that is
        cancelled releases the booking (`booking.Capacity.wait`)."""
        if self._access is None:
            found = self.runtime.access()
            self._access = dataclasses.replace(found, sleep=self._cancellable(found.sleep))
        return self._access

    def _cancellable(self, sleep: Callable[[float], None]) -> Callable[[float], None]:
        def sleeping(seconds: float) -> None:
            if self.cancelled():
                raise Cancelled
            sleep(seconds)

        return sleeping

    def cancelled(self) -> bool:
        return self.journal is not None and (self.journal.directory / CANCEL).exists()

    def measured(self) -> int:
        assert self.journal is not None
        last = {attempt.cell: attempt for attempt in self.journal.attempts}
        return sum(one.reusable for one in last.values())

    def progress(self, step: str) -> None:
        done, total = self.measured(), len(self.plan.cells)
        left = "" if self.ends_at is None else f", {_left(self.ends_at - self.access.clock())}"
        self.say(f"progress: {step}, {done}/{total} cells measured{left}")
        self.status(step=step, cells_measured=done, cells_planned=total)

    # --- The steps ---

    def preflight(self) -> list[str]:
        """The checks that fail. The runtime's own come first: one that cannot measure at all
        stops the preflight before the pool or GitHub is read."""
        failed = [str(one) for one in self.runtime.preflight(self.plan)]
        if Check.MEASUREMENT in failed:
            return failed
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            with tempfile.TemporaryFile(dir=self.root):
                pass
        except OSError:
            failed.append(Check.JOURNAL)
        try:
            sessions = self.access.sessions
            most = admin_pools.max_instances(sessions.pools).get(self.request.pool)
            hours = self.request.window_ms is None or self.request.window_ms <= sessions.session_max_hours * 3_600_000
            if most is None or not 1 <= self.request.instances <= most or not hours:
                failed.append(Check.POOL_LIMITS)
        except _UNREAD:
            failed.append(Check.POOL_LIMITS)
        try:
            self.github.login()
        except (publisher.Unanswered, publisher.Rejected):
            failed.append(Check.DESTINATION)
        return failed

    def open_run(self) -> Journal:
        request, root = self.request, self.root
        if request.resume is False:
            journal = Journal.create(root)
            _write_json(journal.directory / REQUEST, request.saved())
            return journal
        if isinstance(request.resume, str):
            run_id = request.resume
        else:
            run_id = self._find(lambda state: state.get("issue_number") == request.issue)
        saved = _read_json(_run_directory(root, run_id) / REQUEST)
        if saved != request.saved():
            raise ControllerError(Refusal.RESUME_MISMATCH)
        return Journal.open(root, run_id)

    def _find(self, wanted: Callable[[dict[str, Any]], bool]) -> str:
        """The latest run of this request whose journal is `wanted`."""
        for run_id in sorted(journals.runs(self.root), key=lambda one: (self.root / one).stat().st_mtime, reverse=True):
            state = _read_json(self.root / run_id / "journal.json") or {}
            if wanted(state) and _read_json(self.root / run_id / REQUEST) == self.request.saved():
                return run_id
        raise ControllerError(Refusal.NO_RUN_TO_RESUME)

    def experiment(self, journal: Journal) -> Experiment:
        """The experiment the run's issue records: saved with the run, or with an earlier run of
        the issue it adds to, or made for a new issue. It is saved before the issue is created, so
        that a restart reconciles the same record."""
        path = journal.directory / EXPERIMENT
        saved = _read_json(path)
        if saved is None and self.request.issue is not None:
            for run_id in journals.runs(self.root):
                state = _read_json(self.root / run_id / "journal.json") or {}
                found = _read_json(self.root / run_id / EXPERIMENT)
                if state.get("issue_number") == self.request.issue and found is not None:
                    saved = found
                    break
            if saved is None:
                raise ControllerError(Refusal.EXPERIMENT_UNKNOWN)
        if saved is None:
            plan, request = self.plan, self.request
            workload = plan.workload
            question = request.question or (
                f"Does the {request.profile.value} profile of {request.suite} serve a class of "
                f"{request.students} on {request.instances} host(s)?"
            )
            experiment = Experiment(
                question=question,
                source_commit=self.runtime.source_commit(),
                suite=request.suite,
                profile=request.profile,
                workload=plan.workload_hash,
                targets={request.target: self.runtime.requested()},
                seeds=(workload.input_seed, workload.schedule_seed),
                floors=workload.objectives,
            )
            saved = _experiment_json(experiment)
        _write_json(path, saved)
        return _experiment_of(saved)

    def selection(self, window_ms: int) -> tuple[booking.Selection, tuple[int, ...], tuple[int, ...]]:
        """The booking this invocation needs and the cells it runs: the plan's remaining ones, in
        order, that fit the window with the warm-up and the cleanup."""
        assert self.journal is not None
        plan, journal = self.plan, self.journal
        warm_up = plan.cells[0]
        cleanup_ms = plan.spec.estimates.cleanup_ms
        kept = [attempt for attempt in journal.attempts if attempt.reusable]
        served = kept[0].served if kept else plan.workload_hash
        cells = [(cell.identity.cell, plan.reserved_ms(cell)) for cell in plan.cells[1:]]
        try:
            chosen = journal.resume(cells, max(0, window_ms - plan.reserved_ms(warm_up) - cleanup_ms), plan.workload_hash, served)
        except JournalError as error:
            raise ControllerError(Refusal.RESUME_MISMATCH) from error
        batch_ms = plan.reserved_ms(warm_up) + sum(plan.reserved_ms(plan.cells[cell]) for cell in chosen.selected)
        chosen_selection = booking.Selection(
            self.request.pool,
            self.request.instances,
            self.runtime.release(),
            math.ceil(batch_ms / 1000),
            math.ceil(cleanup_ms / 1000),
        )
        return chosen_selection, chosen.selected, chosen.deferred

    def window_ms(self) -> int:
        """The time this invocation may hold: `--for`, or what is left of the designated session."""
        request = self.request
        if not request.existing:
            assert request.window_ms is not None
            return request.window_ms
        sessions = self.access.sessions
        try:
            session = pool_booking.read(sessions.pools.table, request.pool)
        except _UNREAD:
            session = None
        now = self.access.clock()
        left = 0 if session is None else int((rules.end(session, session_max_hours=sessions.session_max_hours) - now) * 1000)
        return left if request.window_ms is None else min(left, request.window_ms)

    def _booking_file(self, intent: journals.Intent) -> Path:
        assert self.journal is not None
        return self.journal.directory / str(intent.payload["file"])

    def reconcile(self, selection: booking.Selection) -> booking.Outcome | None:
        """Every booking the journal intended and has not seen settled, against the pool's record:
        the exact booking still held is waited on again and used, one in doubt is released, one an
        operator changed is theirs. `None` when no booking of the run is held any more."""
        assert self.journal is not None
        journal = self.journal
        books = [one for one in journal.intents if one.action is Action.BOOK and one.status is not IntentStatus.RULED_OUT]
        for intent in books:
            path = self._booking_file(intent)
            saved = booking.Journal.load(path)
            if saved.mode is None or (saved.cleanup is not None and saved.cleanup in _SETTLED):
                if intent.status is IntentStatus.PENDING:
                    journal.confirm(intent.ordinal, {"cleanup": saved.cleanup or booking.Cleanup.NOT_OWNED})
                continue
            capacity = booking.Capacity(selection, self.access, saved)
            found = capacity.reconcile()
            self.say(f"reconciled: booking {intent.payload['file']} {found.value}")
            if found is booking.Cleanup.HELD and intent is books[-1]:
                self.capacity = capacity
                outcome = capacity.wait()
                if intent.status is IntentStatus.PENDING:
                    journal.confirm(intent.ordinal, {"reason": outcome.reason, "cleanup": outcome.cleanup})
                return outcome
            if found not in _SETTLED:
                found = capacity.release()
            self.cleanup = found
            if found not in _SETTLED:
                self.status(cleanup=found.value)
                raise ControllerError(Refusal.BOOKING_UNRESOLVED)
            if intent.status is IntentStatus.PENDING:
                journal.confirm(intent.ordinal, {"cleanup": found})
        return None

    def book(self, selection: booking.Selection, window_ms: int) -> booking.Outcome:
        """The booking, intended in the run journal (which refuses it before the issue), then
        made and waited for by `booking.Capacity.acquire`, whose outcome is kept as it is."""
        assert self.journal is not None
        journal = self.journal
        minutes = None if self.request.existing else math.ceil(window_ms / MINUTE_MS)
        count = sum(one.action is Action.BOOK for one in journal.intents)
        name = f"booking-{count}.json"
        intent = journal.intend(Action.BOOK, {"file": name, "minutes": minutes, "instances": selection.instances})
        self.capacity = booking.Capacity(selection, self.access, booking.Journal.load(journal.directory / name))
        self.say("progress: booking" + ("" if minutes is None else f" {minutes} min") + ", waiting for the hosts")
        outcome = self.capacity.acquire(minutes=minutes)
        journal.confirm(intent.ordinal, {"reason": outcome.reason, "cleanup": outcome.cleanup})
        return outcome

    def continuity(self, selection: booking.Selection) -> Callable[[], Awaitable[booking.Reason | None]]:
        """The probe of the admitted booking that `phases` watches: the record still the one
        admitted, and the selected hosts serving the release."""
        capacity = self.capacity
        assert capacity is not None
        bound = capacity.journal.booking or capacity.journal.designated
        access = self.access

        def probe() -> booking.Reason | None:
            try:
                if pool_booking.read(access.sessions.pools.table, selection.pool) != bound:
                    return booking.Reason.BOOKING_CHANGED
            except _UNREAD:
                return booking.Reason.POOL_STATE_UNREADABLE
            served = list(access.releases())
            if len(served) != selection.instances or any(one != selection.release for one in served):
                return booking.Reason.RELEASE_MISMATCH
            return None

        async def continuity() -> booking.Reason | None:
            return await asyncio.to_thread(probe)

        return continuity

    async def measure(self, outcome: booking.Outcome, selection: booking.Selection, cells: Sequence[int]) -> phases.Ended:
        assert self.journal is not None
        cancel = asyncio.Event()
        admitted = phases.Admitted(outcome, self.continuity(selection))
        deadline = self.ends_at if self.ends_at is not None else self.access.clock()
        watcher = asyncio.create_task(self._watch(cancel))
        try:
            return await self.runtime.measure(self.plan, admitted, self.journal, cells, cancel=cancel, deadline_s=deadline)
        finally:
            watcher.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await watcher

    async def _watch(self, cancel: asyncio.Event) -> None:
        """Turns a cancel request into the cancel event, and shows each newly measured cell."""
        while True:
            if self.cancelled() and not cancel.is_set():
                self.say("progress: cancel requested, stopping the batch")
                cancel.set()
            if self.measured() != self._shown:
                self._shown = self.measured()
                self.progress("measuring")
            await asyncio.sleep(WATCH_SECONDS)

    def release(self) -> None:
        """The conditional stop of this invocation's exact booking, recorded on its own."""
        if self.capacity is not None:
            try:
                self.cleanup = self.capacity.release()
            except Exception:  # noqa: BLE001 - whatever the stop raised, the booking's end bounds it
                self.cleanup = booking.Cleanup.UNCONFIRMED
        self.status(cleanup=self.cleanup.value)
        self.say(f"cleanup: {self.cleanup.value}")

    def write_report(self) -> tuple[Scorecard, report.Bundle, report.Derived, Path] | None:
        """The local report: the run's bundle and its regenerated scorecard, in the run's
        directory. `None` when there is no evidence, or the report refuses it."""
        assert self.journal is not None
        directory = self.journal.directory / BUNDLE
        staging = self.journal.directory / (BUNDLE + ".new")
        shutil.rmtree(staging, ignore_errors=True)
        try:
            if not self.runtime.write_bundle(self.plan, self.journal, staging):
                return None
            bundle = report.load(staging)
            rate, source = self.request.rate
            derived = report.regenerate(bundle, usd_per_host_hour=rate, rate_source=source)
            report.write_derived(staging, derived)
        except report.ReportError as refused:
            self.say(f"report: refused, {refused.reason.value}")
            shutil.rmtree(staging, ignore_errors=True)
            return None
        shutil.rmtree(directory, ignore_errors=True)
        staging.rename(directory)
        return scorecard(json.loads(derived.summary)), bundle, derived, directory

    def run(self) -> Exit:
        request = self.request
        failed = self.preflight()
        if failed:
            self.say(f"refused: {Refusal.PREFLIGHT_FAILED.value}: {', '.join(failed)}")
            return Exit.INCOMPLETE
        self.say("progress: preflight passed")
        self.journal = self.open_run()
        with self.journal as journal:
            # A cancel request was for the invocation that read it, not for this one.
            (journal.directory / CANCEL).unlink(missing_ok=True)
            self.say(f"run: {journal.run_id}")
            self.status(run_id=journal.run_id, step="issue", cleanup=self.cleanup.value)
            try:
                number = self.publisher.open_experiment(journal, self.experiment(journal), request.issue)
            except PublishError as refused:
                self.say(f"refused: {refused.reason.value}, nothing was booked")
                self.status(step="refused", refused=refused.reason.value, exit=int(Exit.INCOMPLETE))
                return Exit.INCOMPLETE
            url = issue_url(self.github.repository, number)
            self.say(f"issue: {url}")
            self.status(issue=url)
            ending = self._book_and_measure()
            report_paths: list[str] = []
            made = self.write_report()
            card = None if made is None else made[0]
            if made is not None:
                report_paths = [str(made[3] / report.REPORT), str(made[3] / report.SUMMARY)]
            capacity = overall({} if card is None else card.capacity)
            quality = overall({} if card is None else card.quality)
            code = exit_code(ending, capacity, quality)
            self.say(f"capacity: {capacity.value}")
            for row in () if card is None else card.capacity_rows:
                self.say(f"  limiting {row}")
            self.say(f"quality: {quality.value}")
            for row in () if card is None else card.quality_rows:
                self.say(f"  limiting {row}")
            for path in report_paths:
                self.say(f"report: {path}")
            self.status(
                ending=ending.value,
                reason=None if self.reason is None else self.reason.value,
                capacity=capacity.value,
                quality=quality.value,
                capacity_rows=[] if card is None else list(card.capacity_rows),
                quality_rows=[] if card is None else list(card.quality_rows),
                report=report_paths,
                exit=int(code),
            )
            box = self.publish(journal, ending, made)
            self.status(delivered=box.delivered, waiting=box.waiting)
            if box.waiting:
                self.say(f"publication: pending ({box.waiting}), scripts/evaluate.sh publish --resume {journal.run_id}")
            else:
                self.say("publication: delivered")
            self.say(f"exit: {int(code)} ({code.name.lower().replace('_', ' ')})")
        return code

    def _book_and_measure(self) -> Ending:
        """Steps 2 to 4: the booking, the batch, and the cleanup in any case. The ending says how
        far the run got; `self.reason` why it ended short."""
        assert self.journal is not None
        ended: phases.Ended | None = None
        try:
            window = self.window_ms()
            selection, cells, deferred = self.selection(window)
            outcome = self.reconcile(selection)
            if outcome is None and (cells or self.measured() < len(self.plan.cells)):
                if not cells:
                    self.say(f"refused: {booking.Reason.WINDOW_TOO_SHORT.value} for the next cell")
                    self.reason = Reason.WINDOW_EXHAUSTED
                    return Ending.INTERRUPTED
                if self.cancelled():
                    raise Cancelled
                outcome = self.book(selection, window)
            if outcome is not None:
                self.cleanup = outcome.cleanup
                if not outcome.ready:
                    assert outcome.reason is not None
                    self.say(f"capacity: {outcome.reason.value}")
                    self.reason = _DECLINED.get(outcome.reason, Reason.CAPACITY_UNAVAILABLE)
                    return Ending.FAILED
                session = outcome.session
                assert session is not None
                self.ends_at = rules.end(session, session_max_hours=self.access.sessions.session_max_hours)
                if self.request.window_ms is not None:
                    self.ends_at = min(self.ends_at, self.access.clock() + self.request.window_ms / 1000)
                self.progress(f"hosts ready, measuring {len(cells)} cell(s) after the warm-up")
                ended = asyncio.run(self.measure(outcome, selection, cells))
                self.progress(f"measurement ended, {ended.value}")
            if ended is not None and ended is not phases.Ended.COMPLETED:
                self.reason = _ENDED[ended]
            elif deferred:
                self.reason = Reason.WINDOW_EXHAUSTED
        except (Cancelled, KeyboardInterrupt):
            self.say("progress: cancelled")
            self.reason = Reason.OPERATOR_CANCELLED
            return Ending.INTERRUPTED
        except phases.PhaseError as refused:
            self.say(f"refused: {refused.reason.value}, nothing was measured")
            self.reason = Reason.INVALID_EVIDENCE
            return Ending.FAILED
        except ControllerError as refused:
            self.say(f"refused: {refused.reason}")
            unresolved = refused.reason == Refusal.BOOKING_UNRESOLVED
            self.reason = Reason.CAPACITY_UNAVAILABLE if unresolved else Reason.INVALID_EVIDENCE
            return Ending.FAILED
        except Exception as error:  # noqa: BLE001 - the driver's fault ends the run, and is named
            self.say(f"driver-error: {type(error).__name__}")
            self.reason = Reason.DRIVER_ERROR
            return Ending.FAILED
        finally:
            self.release()
        if self.reason is None and self.measured() == len(self.plan.cells):
            return Ending.COMPLETED
        self.reason = self.reason or Reason.WINDOW_EXHAUSTED
        return Ending.INTERRUPTED

    def publish(
        self, journal: Journal, ending: Ending, made: tuple[Scorecard, report.Bundle, report.Derived, Path] | None
    ) -> publisher.Outbox:
        """The terminal comment of this invocation, journaled before it is sent."""
        invocation = sum(
            one.action is Action.DELIVER and one.status is not IntentStatus.RULED_OUT and one.payload.get("kind") == "run"
            for one in journal.intents
        )
        card = None if made is None else made[0]
        observed: Settings | dict[str, object] = {}
        hours, digest = 0.0, report.digest_of("")
        if made is not None:
            bundle, derived = made[1], made[2]
            observed, digest = bundle.manifest.observed, derived.digest
            hours = round(
                sum(
                    (one.record.ended_ms - one.record.started_ms) * (one.record.hosts_observed or 0)
                    for one in bundle.attempts
                )
                / 3_600_000,
                6,
            )
        served = observed.host_count if isinstance(observed, Settings) else None
        completed = self.measured()
        result = RunResult(
            run_id=journal.run_id,
            ending=ending,
            cells_completed=completed,
            cells_planned=len(self.plan.cells),
            observed=observed,
            requested_hosts=self.request.instances,
            served_hosts=served or 0,
            capacity={} if card is None else card.capacity,
            quality={} if card is None else card.quality,
            failures=0 if card is None else card.failures,
            attempts=0 if card is None else card.attempts,
            tasks={} if card is None else card.tasks,
            host_hours=hours,
            cleanup=Cleanup(self.cleanup.value),
            bundle_digest=digest,
            reason=None if ending is Ending.COMPLETED else self.reason,
            ttft_p95_ms=None if card is None else card.ttft_p95_ms,
            speed_p50=None if card is None else card.speed_p50,
            speed_p10=None if card is None else card.speed_p10,
        )
        try:
            return self.publisher.publish_run(journal, result, invocation=invocation)
        except PublishError as refused:
            self.say(f"publication: refused, {refused.reason.value}")
            return publisher.outbox(journal)


def execute(request: Request, *, connect: Connect, root: Path = journals.DEFAULT_ROOT, out: IO[str]) -> Exit:
    """One `run`: the whole invocation, bounded by its booking, with every lookup scoped to the
    request's pool and repository. The exit code is `Exit`'s."""
    if not request.existing and (request.window_ms is None or request.window_ms <= 0):
        print(f"refused: {Refusal.INVALID_REQUEST.value}: a managed booking needs --for", file=out)
        return Exit.INCOMPLETE
    if request.issue is None and request.resume is True:
        print(f"refused: {Refusal.INVALID_REQUEST.value}: a resume names its run or its issue", file=out)
        return Exit.INCOMPLETE
    try:
        plan = planning.expand(
            planning.load_suite(request.suite),
            request.profile,
            request.students,
            input_seed=request.input_seed,
            schedule_seed=request.schedule_seed,
        )
    except planning.PlanError as refused:
        print(f"refused: {refused.reason.value}", file=out)
        return Exit.INCOMPLETE
    scope = Scope(request.pool, request.repository)
    with connect(scope) as runtime:
        if runtime.scope != scope or runtime.github().repository != scope.repository:
            print(f"refused: {Refusal.SCOPE_MISMATCH.value}", file=out)
            return Exit.INCOMPLETE
        try:
            return _Invocation(request, plan, runtime, root, out).run()
        except (ControllerError, JournalError) as refused:
            print(f"refused: {refused}", file=out)
            return Exit.INCOMPLETE


