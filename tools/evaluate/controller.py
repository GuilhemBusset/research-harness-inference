def _write_json(path: Path, value: Mapping[str, Any]) -> None:
    """Replaces the file whole, private to its owner."""
    beside = path.with_name(path.name + ".tmp")
    fd = os.open(beside, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as file:
        file.write(json.dumps(value, indent=2, sort_keys=True) + "\n")
    os.replace(beside, path)


def _read_json(path: Path) -> dict[str, Any] | None:
    try:
        found = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return found if isinstance(found, dict) else None


def _run_directory(root: Path, run_id: str) -> Path:
    if run_id not in journals.runs(root):
        raise ControllerError(Refusal.NO_SUCH_RUN)
    return root / run_id


def saved_state(root: Path, run_id: str) -> dict[str, Any]:
    """The run journal's state as its file holds it, read without taking the run: what `status`
    and the search for a run show while a driver owns it."""
    found = _read_json(_run_directory(root, run_id) / "journal.json")
    if found is None:
        raise ControllerError(Refusal.NO_SUCH_RUN)
    return found


def _deliveries(state: Mapping[str, Any]) -> tuple[int, int]:
    """The comments delivered, and those waiting (pending or queued)."""
    kinds = [one["status"] for one in state.get("intents", ()) if one.get("action") == Action.DELIVER]
    waiting = (IntentStatus.PENDING, IntentStatus.QUEUED)
    return sum(one == IntentStatus.CONFIRMED for one in kinds), sum(one in waiting for one in kinds)


def _experiment_json(experiment: Experiment) -> dict[str, Any]:
    targets = {
        name: (settings.to_json() if isinstance(settings, Settings) else dict(settings))
        for name, settings in experiment.targets.items()
    }
    floors = experiment.floors
    return {
        "question": experiment.question,
        "source_commit": experiment.source_commit,
        "suite": experiment.suite,
        "profile": experiment.profile.value,
        "workload": experiment.workload,
        "targets": {name: {key: value for key, value in one.items() if value is not None} for name, one in targets.items()},
        "seeds": list(experiment.seeds),
        "floors": floors.to_json() if isinstance(floors, Objectives) else dict(floors),
    }


def _experiment_of(saved: Mapping[str, Any]) -> Experiment:
    return Experiment(
        question=saved["question"],
        source_commit=saved["source_commit"],
        suite=saved["suite"],
        profile=Profile(saved["profile"]),
        workload=saved["workload"],
        targets=saved["targets"],
        seeds=tuple(saved["seeds"]),
        floors=saved["floors"],
    )


def issue_url(repository: str, number: int) -> str:
    return f"https://github.com/{repository}/issues/{number}"


def _left(seconds: float) -> str:
    whole = max(0, int(seconds))
    return f"{whole // 3600}h {whole % 3600 // 60:02d}m left"


