    scope: Scope

    def github(self) -> publisher.GitHub:
        """GitHub as the driver, in the scope's repository."""
        ...

    def access(self) -> booking.Access:
        """The deployment's pool sessions, and the probes of the scope's pool."""
        ...

    def release(self) -> str:
        """The release every selected host must serve."""
        ...

    def requested(self) -> Settings:
        """The public settings the pool is deployed to serve: the experiment's target."""
        ...

    def source_commit(self) -> str: ...

    def preflight(self, plan: Plan) -> Sequence[str]:
        """The members of `Check` the runtime's own measurement fails, empty when it can run."""
        ...

