_SHAPE_VERDICT = {"pass": Verdict.PASS, "known_miss": Verdict.MEASURED_MISS}


@dataclass(frozen=True)
class Scorecard:
    """What the run's summary says, as the operator and the comment read it."""

    capacity: dict[Shape, Verdict]
    quality: dict[Shape, Verdict]
    capacity_rows: tuple[str, ...]
    quality_rows: tuple[str, ...]
    failures: int
    attempts: int
    tasks: dict[Harness, tuple[int, int]]
    ttft_p95_ms: float | None
    speed_p50: float | None
    speed_p10: float | None


def overall(verdicts: Mapping[Shape, Verdict]) -> Verdict:
    """One verdict over the shapes: a miss in any, a pass only when every shape passed."""
    if not verdicts:
        return Verdict.NOT_MEASURED
    if Verdict.MEASURED_MISS in verdicts.values():
        return Verdict.MEASURED_MISS
    if set(verdicts) == set(Shape) and all(one is Verdict.PASS for one in verdicts.values()):
        return Verdict.PASS
    return Verdict.INCONCLUSIVE


def exit_code(ending: Ending, capacity: Verdict, quality: Verdict) -> Exit:
    """The exit of `run`, from the verdicts and the ending alone. Only a completed profile has a
    verdict of its own: an invocation that failed or was interrupted is incomplete evidence,
    whatever it measured, and its verdict rows still show a miss it observed."""
    if ending is not Ending.COMPLETED:
        return Exit.INCOMPLETE
    if Verdict.MEASURED_MISS in (capacity, quality):
        return Exit.MEASURED_MISS
    if capacity is Verdict.PASS and quality is Verdict.PASS:
        return Exit.PASS
    return Exit.INCOMPLETE


def _numbers(values: object) -> list[float]:
    return [float(one) for one in values if isinstance(one, int | float)] if isinstance(values, list) else []


def _class_load_shown(summary: Mapping[str, Any], shape: Shape) -> bool:
    """Whether the report shows the shape's tasks ran under the class load (`load_evidence`)."""
    rows = summary.get("class_load_evidence", {}).get(shape.value)
    return isinstance(rows, list) and bool(rows) and all(isinstance(row, dict) and row.get("status") == "met" for row in rows)


def scorecard(summary: Mapping[str, Any]) -> Scorecard:
    """The verdicts by shape and their limiting rows: capacity at class size as the report graded
    it; quality as the absolute floor of each family of the shape at every load the profile
    measured, low load included. A floor missed at any load is a miss. A pass needs every family
    of the shape at class load, every floor read met, and the class load shown to have been there
    while the tasks ran: without that evidence, tasks that met their floors are inconclusive."""
    capacity: dict[Shape, Verdict] = {}
    capacity_rows: list[str] = []
    ttft: list[float] = []
    p50: list[float] = []
    p10: list[float] = []
    for shape in Shape:
        found = summary.get("capacity", {}).get(shape.value)
        if not isinstance(found, dict):
            continue
        capacity[shape] = _SHAPE_VERDICT.get(found.get("verdict"), Verdict.INCONCLUSIVE)
        row = found.get("limiting_row")
        if isinstance(row, dict):
            missed = "missed" if row.get("missed") else "met"
            capacity_rows.append(
                f"{shape.value}: {row.get('floor')} {missed}, headroom {row.get('headroom')}, "
                f"repetition {row.get('repetition')}"
            )
        spread = found.get("spread", {})
        ttft += _numbers(spread.get("ttft_p95_ms"))
        p50 += _numbers(spread.get("speed_p50_tokens_per_s"))
        p10 += _numbers(spread.get("speed_p10_tokens_per_s"))
    quality: dict[Shape, Verdict] = {}
    quality_rows: list[str] = []
    loads = summary.get("quality", {})
    by_load = {
        name: [cell for cell in load.get("cells", []) if isinstance(cell, dict)]
        for name, load in loads.items()
        if isinstance(load, dict)
    }
    for shape in Shape:
        families = {family.value for family in SHAPE_FAMILIES[shape]}
        cells = [(name, cell) for name, held in by_load.items() for cell in held if cell.get("family") in families]
        if not cells:
            continue
        outcomes = {cell.get("floor_outcome") for _, cell in cells}
        at_class = {cell.get("family") for name, cell in cells if name == "class_load"}
        shown = _class_load_shown(summary, shape)
        if "fail" in outcomes:
            quality[shape] = Verdict.MEASURED_MISS
        elif outcomes == {"pass"} and at_class == families and shown:
            quality[shape] = Verdict.PASS
        else:
            quality[shape] = Verdict.INCONCLUSIVE
        rated = [
            (name, cell)
            for name, cell in cells
            if isinstance(cell.get("rate"), int | float) and isinstance(cell.get("floor"), int | float)
        ]
        failing = [(name, cell) for name, cell in cells if cell.get("floor_outcome") == "fail"]
        for name, cell in failing or sorted(rated, key=lambda one: one[1]["rate"] - one[1]["floor"])[:1]:
            quality_rows.append(
                f"{shape.value}: {cell['family']} on {cell['harness']} at {name} {cell.get('floor_outcome')}, "
                f"rate {cell.get('rate')} against {cell.get('floor')}"
            )
        if not shown:
            quality_rows.append(f"{shape.value}: class load not shown")
    sweep = [row for row in summary.get("capacity_sweep", []) if isinstance(row, dict)]
    tasks: dict[Harness, tuple[int, int]] = {}
    for load in loads.values():
        for cell in load.get("cells", []) if isinstance(load, dict) else []:
            harness = Harness(cell["harness"])
            passed, attempted = tasks.get(harness, (0, 0))
            tasks[harness] = (passed + int(cell.get("successes") or 0), attempted + int(cell.get("attempts") or 0))
    return Scorecard(
        capacity=capacity,
        quality=quality,
        capacity_rows=tuple(capacity_rows),
        quality_rows=tuple(quality_rows),
        failures=sum(int(row.get("failed") or 0) for row in sweep),
        attempts=sum(int(row.get("attempts") or 0) for row in sweep),
        tasks=tasks,
        ttft_p95_ms=max(ttft) if ttft else None,
        speed_p50=min(p50) if p50 else None,
        speed_p10=min(p10) if p10 else None,
    )


