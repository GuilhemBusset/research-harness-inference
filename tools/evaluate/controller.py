@dataclass(frozen=True)
class Request:
    """One typed `run`: what the terminal's flags and the skill's request both are. `window_ms`
    bounds a managed booking (`--for`); `existing` designates the operator's own session, which
    `window_ms` then bounds only if given. `issue` is `None` for a new experiment issue. `resume`
    continues a run: `True` finds it by its issue and request, a string names its run ID. `rate`
    is the operator's host price, if given; without it the report prices the deployed pool's
    instance type, and `fallback_rate` only when the deployment does not say."""

    suite: str
    profile: Profile
    pool: str
    students: int
    instances: int
    repository: str
    window_ms: int | None = None
    existing: bool = False
    issue: int | None = None
    resume: bool | str = False
    question: str | None = None
    target: str = "reference"
    input_seed: int | None = None
    schedule_seed: int | None = None
    rate: tuple[float, str] | None = None
    fallback_rate: tuple[float, str] = (1.0, "example")

    def saved(self) -> dict[str, Any]:
        """What a resume must request again to continue the run: the workload and the scope."""
        return {
            "suite": self.suite,
            "profile": self.profile.value,
            "pool": self.pool,
            "students": self.students,
            "instances": self.instances,
            "repository": self.repository,
            "input_seed": self.input_seed,
            "schedule_seed": self.schedule_seed,
        }


class Runtime(Protocol):
    """The scoped lookups of one invocation, bound to `scope`."""

    scope: Scope

    def github(self) -> publisher.GitHub:
        """GitHub as the driver, in the scope's repository."""
        ...

    def access(self) -> booking.Access:
        """The deployment's pool sessions, and the probes of the scope's pool."""
        ...

    def release(self) -> str:
        """The release every selected host must serve."""
        ...

    def requested(self) -> Settings:
        """The public settings the pool is deployed to serve: the experiment's target."""
        ...

    def source_commit(self) -> str: ...

    def clock(self) -> float:
        """The time in seconds since the epoch, as the pool's access reads it: what the
        invocation's one deadline is counted from."""
        ...

    def preflight(self, plan: Plan) -> Sequence[str]:
        """The members of `Check` the runtime's own measurement fails, empty when it can run."""
        ...

    async def measure(
        self,
        plan: Plan,
        admitted: phases.Admitted,
        journal: Journal,
        cells: Sequence[int],
        *,
        cancel: asyncio.Event,
        deadline_s: float,
    ) -> phases.Ended:
        """Runs the warm-up and `cells` in the admitted booking, each journaled."""
        ...

    def write_bundle(self, plan: Plan, journal: Journal, directory: Path) -> bool:
        """Writes the run's evidence bundle into `directory`, which does not exist. False when
        there is no evidence to write."""
        ...


