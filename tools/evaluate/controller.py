"""The operator controller: one bounded invocation of an evaluation, from the terminal or from the
skill's driver (docs/design/agent-session-evaluation.md, "How the operator runs it").

`execute` runs one `Request` in the design's order, and each step is the existing module's:

1. **Preflight**, before anything is created: a writable journal root, the selected pool deployed
   with room for the hosts and the minutes (`rhi_admin.pools.max_instances`, `session_max_hours`),
   the experiment's destination answering as the driver (`publisher.GitHub.login`), and what the
   runtime checks of its own measurement (`Runtime.preflight`: harness versions, canaries,
   telemetry). A failed check is named from `Check` and nothing is created, booked or sent.
2. **The record, then the booking.** The run journal (`journal.Journal`) is created, which saves
   the run ID, or the run named by `--resume` is opened. The experiment's issue is created or
   adopted (`publisher.Publisher.open_experiment`) and its number journaled. Only then is the
   booking intended in the run journal (`journal.Action.BOOK`, which the journal refuses before
   the issue) and made (`booking.Capacity.acquire`): a managed booking for `--for`, or the
   designated session with `--session existing`. `acquire` waits for the hosts itself, and its
   outcome is used as it is: a refusal keeps its reason (`pool-already-booked`,
   `capacity-unavailable`, ...).
3. **Measuring.** `Runtime.measure` runs the selected cells (`phases.run` in the live runtime)
   against the admitted booking, with the cancel event and the invocation's deadline. The cells are
   the plan's remaining ones that fit the window (`journal.Journal.resume`): a cell checkpointed
   valid is kept whatever it measured, an interrupted one is run again whole and its earlier
   attempt stays.
4. **Cleanup**, on completion, error or cancellation, before anything is reported or published:
   `booking.Capacity.release`, the conditional stop of the exact booking this invocation made,
   which writes nothing to a record someone else changed (`yielded`) and nothing in a designated
   session. Its outcome is saved in the booking's own journal and in the run's status, apart from
   the measurement and the publication.
5. **The local report**: the evidence bundle of the run (`Runtime.write_bundle`), its scorecard
   regenerated by `report.regenerate` beside it, and the two verdicts and their limiting rows read
   from the summary.
6. **The terminal comment** (`publisher.Publisher.publish_run`), rendered from allow-listed fields,
   scanned and journaled before it is sent. A GitHub that does not answer leaves it pending: the
   verdict and the exit code do not change, and `publish --resume` delivers it later.

**Restart.** A run is resumed by its ID, or by its issue and the same request. Before anything is
booked, every booking the journal intended and has not seen settled is reconciled against the
selected pool (`booking.Capacity.reconcile`): one that is still the exact booking is waited on and
used, one whose write or stop is in doubt is released, one an operator changed is left to them.
A booking that stays in doubt stops the invocation before it books again.

**Scoped lookups.** Everything outside the driver comes through one `Runtime`, opened by `connect`
for one `Scope`, the selected pool and the experiment's repository, and closed with the invocation:
the pool-state table and the scaler of the deployment, the gateway and telemetry of that pool, the
harnesses, and GitHub as the driver in that repository. `execute` refuses a runtime bound to
another scope before anything is created (`Refusal.SCOPE_MISMATCH`). Nothing is read from a global,
and no credential leaves the runtime.

**What the operator sees**: the run ID, progress (the step, cells measured out of the plan, the
time left in the booking), the issue's URL, both verdicts with their limiting rows, the report's
paths, the cleanup and the publication, delivered or pending. The run directory's `status.json`
holds the same (`status`). The exit code (`Exit`) is 0 for a completed profile that meets its
applicable floors, 1 for a measured miss, and 2 for invalid, incomplete or inconclusive evidence and
for a refusal. It depends on the verdicts and the ending only, never on the publication.

The run directory is private: it holds the booking's journal and the comments' text. Nothing in it
is published but the comments and an explicit export.
"""

