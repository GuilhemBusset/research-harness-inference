def _write_json(path: Path, value: Mapping[str, Any]) -> None:
    """Replaces the file whole, private to its owner."""
    beside = path.with_name(path.name + ".tmp")
    fd = os.open(beside, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as file:
        file.write(json.dumps(value, indent=2, sort_keys=True) + "\n")
    os.replace(beside, path)


def _read_json(path: Path) -> dict[str, Any] | None:
    try:
        found = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return found if isinstance(found, dict) else None


def _run_directory(root: Path, run_id: str) -> Path:
    if run_id not in journals.runs(root):
        raise ControllerError(Refusal.NO_SUCH_RUN)
    return root / run_id


def saved_state(root: Path, run_id: str) -> dict[str, Any]:
    """The run journal's state as its file holds it, read without taking the run: what `status`
    and the search for a run show while a driver owns it."""
    found = _read_json(_run_directory(root, run_id) / "journal.json")
    if found is None:
        raise ControllerError(Refusal.NO_SUCH_RUN)
    return found


def _deliveries(state: Mapping[str, Any]) -> tuple[int, int]:
    """The comments delivered, and those waiting (pending or queued)."""
    kinds = [one["status"] for one in state.get("intents", ()) if one.get("action") == Action.DELIVER]
    waiting = (IntentStatus.PENDING, IntentStatus.QUEUED)
    return sum(one == IntentStatus.CONFIRMED for one in kinds), sum(one in waiting for one in kinds)


class Publication(StrEnum):
    """Where a run's publication stands, apart from its verdicts."""

    # Every write the run made was confirmed by GitHub: its issue's creation, its comments.
    DELIVERED = "delivered"
    # A write waits: the issue's creation or a comment, in doubt or queued. `publish --resume`.
    PENDING = "pending"
    # A comment was refused before anything was sent (a field or the hygiene scan): not published.
    REFUSED = "refused"
    # Nothing of the run was written: an issue the operator selected and no comment yet.
    NONE = "none"


def publication(state: Mapping[str, Any], refused: bool) -> Publication:
    """The run's publication from its saved journal, and whether a comment of it was refused."""
    intents = [one for one in state.get("intents", ()) if one.get("action") in (Action.CREATE_ISSUE, Action.DELIVER)]
    if any(one.get("status") in (IntentStatus.PENDING, IntentStatus.QUEUED) for one in intents):
        return Publication.PENDING
    if refused:
        return Publication.REFUSED
    if any(one.get("status") == IntentStatus.CONFIRMED for one in intents):
        return Publication.DELIVERED
    return Publication.NONE


def _issue_record(state: Mapping[str, Any]) -> Mapping[str, Any] | None:
    """What a run's saved journal says its issue is: the payload of its creation, or the record of
    the issue it adopted. Its repository and its experiment's identity are among it."""
    creations = [
        one
        for one in state.get("intents", ())
        if one.get("action") == Action.CREATE_ISSUE and one.get("status") != IntentStatus.RULED_OUT
    ]
    found = creations[-1].get("payload") if creations else state.get("issue_record")
    return found if isinstance(found, dict) else None


